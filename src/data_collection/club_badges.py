"""Generate club badge SVGs and the generic player placeholder.

**These are not the clubs' real crests.** Premier League crests are trademarked and
copyrighted; Wikimedia Commons excludes them by policy, and a survey of all 20 clubs
found exactly one crest SVG under a free licence - a 1930 Arsenal crest. So rather than
mislabel trademarked artwork as open, the project draws its own: a monogram in each
club's real colours, authored here and therefore genuinely ours to license.

Output is deterministic - the same slug always produces a byte-identical file - so
regenerating never shows up as a diff.
"""

from __future__ import annotations

import json
import logging
import re
from datetime import UTC, datetime
from pathlib import Path

